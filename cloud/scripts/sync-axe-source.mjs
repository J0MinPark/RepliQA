import fs from 'node:fs/promises';
// Preserve upstream browser bytes before bundling. axe.source uses Function#toString,
// which can capture bundler-only helpers such as __name and fail in the page.
const pkg=JSON.parse(await fs.readFile(new URL('../node_modules/axe-core/package.json',import.meta.url),'utf8'));
const source=await fs.readFile(new URL('../node_modules/axe-core/axe.min.js',import.meta.url),'utf8');
const output=new URL('../src/axe-source.mjs',import.meta.url);
await fs.writeFile(output,`// Generated by scripts/sync-axe-source.mjs; do not edit.\n// axe-core ${pkg.version}, unmodified browser source, MPL-2.0. See public/third-party-notices.txt.\nexport const axeVersion=${JSON.stringify(pkg.version)};\nexport const axeSource=${JSON.stringify(source)};\n`);
