// recordRoute.js가 기록한 사람의 실제 행동(클릭/입력/제출 이벤트, 입력값 자체는 포함 안
// 됨)을 RepliQA 체크포인트 목표 한 줄로 요약하는 프롬프트. geminiAdapter.js가 실제 호출을
// 담당하고, 이 파일은 프롬프트 구성만 순수 함수로 분리해서 유닛 테스트 가능하게 한다
// (reportPrompt.js와 같은 패턴).
//
// 중요: 여기서 만드는 목표 문장은 "고정된 실행 스크립트"가 아니다 — RepliQA는 실행할
// 때마다 이 목표 문장 하나만 보고 화면을 보면서 매번 새로 판단한다(코드 없이 자연어로
// 아무 사이트나 다루는 RepliQA의 핵심 철학과 충돌하지 않기 위함). 그래서 프롬프트도
// 클릭 좌표/구현 디테일이 아니라 "무엇을 달성했는지"에 집중하도록 유도한다.
function buildRecordingSummaryPrompt({ events, url }) {
  const prompt = `너는 사용자가 실제로 웹사이트에서 수행한 행동 기록을 보고, 그 행동들이
하나의 QA 체크포인트로서 어떤 목표를 달성했는지 한 줄의 자연어 목표로 요약하는 봇이다.

행동 기록은 클릭(click)/양식 입력(input — 실제 입력값은 포함되지 않고 어떤 필드를 채웠는지만
있음)/제출(submit) 이벤트의 시간순 목록이다. 이 기록을 보고 RepliQA 체크포인트 목표 문장
하나를 만들어라(예: "장바구니에 상품 담기", "회원가입 완료하기", "검색해서 결과 확인하기").

목표 문장은 "무엇을 달성해야 하는지"에만 집중해라 — 클릭 좌표나 구현 디테일을 언급하지 마라.
RepliQA는 실행할 때마다 이 목표 문장 하나만 보고 화면을 보면서 처음부터 새로 판단하기
때문에, 특정 버튼 텍스트 하나에 과하게 의존하는 표현보다는 사용자 관점의 의도를 담아라.

<시작_url>${url}</시작_url>
<기록된_행동>
${JSON.stringify(events)}
</기록된_행동>

반드시 아래 JSON 스키마로만 응답해라. 다른 설명은 붙이지 마라:
{"goal": "체크포인트 목표 한 줄"}`;

  return { prompt };
}

module.exports = { buildRecordingSummaryPrompt };
